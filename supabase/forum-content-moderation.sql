create or replace function public.normalize_forum_moderation_text(input_text text)
returns text
language sql
immutable
set search_path = public
as $$
  select regexp_replace(
    replace(
      replace(
        translate(
          lower(coalesce(input_text, '')),
          'ＡＢＣＤＥＦＧＨＩＪＫＬＭＮＯＰＱＲＳＴＵＶＷＸＹＺａｂｃｄｅｆｇｈｉｊｋｌｍｎｏｐｑｒｓｔｕｖｗｘｙｚ０１２３４５６７８９',
          'abcdefghijklmnopqrstuvwxyzabcdefghijklmnopqrstuvwxyz0123456789'
        ),
        chr(8203),
        ''
      ),
      chr(65279),
      ''
    ),
    '[[:space:][:punct:]，。！？、；：…—（）【】《》“”‘’·]+',
    '',
    'g'
  );
$$;

create or replace function public.forum_content_is_blocked(input_text text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.forum_blocked_terms blocked
    where blocked.enabled
      and public.normalize_forum_moderation_text(blocked.term) <> ''
      and position(
        public.normalize_forum_moderation_text(blocked.term)
        in public.normalize_forum_moderation_text(input_text)
      ) > 0
  );
$$;

create or replace function public.moderate_forum_post_content()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.forum_content_is_blocked(coalesce(new.title, '') || ' ' || coalesce(new.content, '')) then
    raise exception using
      errcode = 'P0001',
      message = '内容包含辱骂、威胁或其他不友善用语，请修改后再发布。';
  end if;
  return new;
end;
$$;

create or replace function public.moderate_forum_reply_content()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.forum_content_is_blocked(new.content) then
    raise exception using
      errcode = 'P0001',
      message = '内容包含辱骂、威胁或其他不友善用语，请修改后再发布。';
  end if;
  return new;
end;
$$;

drop trigger if exists moderate_forum_posts_before_write on public.forum_posts;
create trigger moderate_forum_posts_before_write
before insert or update of title, content on public.forum_posts
for each row execute function public.moderate_forum_post_content();

drop trigger if exists moderate_forum_replies_before_write on public.forum_replies;
create trigger moderate_forum_replies_before_write
before insert or update of content on public.forum_replies
for each row execute function public.moderate_forum_reply_content();

