-- Run this file in the Supabase SQL Editor after the forum_posts and forum_replies tables exist.
-- The browser performs the same check for immediate feedback; these triggers are the authoritative fallback.

create table if not exists public.forum_blocked_terms (
  id bigint generated by default as identity primary key,
  term text not null unique,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  constraint forum_blocked_terms_not_blank check (length(trim(term)) > 0)
);

alter table public.forum_blocked_terms enable row level security;
revoke all on public.forum_blocked_terms from anon, authenticated;

